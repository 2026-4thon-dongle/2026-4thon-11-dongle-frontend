/**
 * 지역의 소식 2개 중 하나를 고른다. 같은 편지에서는 같은 지역이면 늘 같은 소식이 나온다(편지 번호와 지역으로 정한다).
 * @param {string|number} letterId 편지 번호
 * @param {string} sido 시·도 약칭(서울, 충남 …)
 * @returns {string} 소식 한 줄. 모르는 지역이면 ''
 */
export function pickRegionNews(letterId, sido) {
  const news = REGION_NEWS[sido]
  if (!news) return ''
  const seed = [...`${letterId}:${sido}`].reduce((sum, char) => sum + char.charCodeAt(0), 0)
  return news[seed % news.length]
}
